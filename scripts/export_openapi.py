"""Export the OpenAPI (Swagger) spec of the API to openapi.yaml.

Usage: python scripts/export_openapi.py [output-path]
The spec is generated from the FastAPI app, so it always matches the code; tests/test_openapi.py
fails if the committed file is out of date.
"""

import sys
from pathlib import Path

import yaml

from rag_service.config import Settings
from rag_service.main import create_app

ROOT = Path(__file__).resolve().parents[1]


def render() -> str:
    spec = create_app(Settings()).openapi()
    header = "# Generated by scripts/export_openapi.py from the FastAPI app. Do not edit by hand.\n"
    return header + yaml.safe_dump(spec, sort_keys=False, allow_unicode=True, width=100)


def main() -> None:
    out = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "openapi.yaml"
    out.write_text(render(), encoding="utf-8")
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
